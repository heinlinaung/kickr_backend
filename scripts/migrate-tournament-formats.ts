/**
 * Migrate tournaments to formats, phases and the new lifecycle.
 *
 * WHY
 * ---
 * Tournaments had `type: knockout | league` and `status: registering |
 * ongoing | finished`. Formats (docs/change-logs/2026-10-29_tournament_formats.md)
 * replace them with `format` + `settings` and an eight-step lifecycle, and
 * registrations gain an approval `status`.
 *
 * MAPPING
 * -------
 *   status registering -> REGISTRATION_OPEN
 *   status ongoing     -> KNOCKOUT_IN_PROGRESS or LEAGUE_IN_PROGRESS, by type
 *   status finished    -> COMPLETED
 *   type knockout      -> format KNOCKOUT, default knockout settings
 *   type league        -> format LEAGUE, default league settings
 *   tournamentteams without status -> APPROVED (they joined with no approval)
 *
 * The service already reads registrations without a status as approved and
 * fills default settings on load, so this only matters for the status enum,
 * which Mongoose now validates on save.
 *
 * Old `tournamentmatches` rows (scoreA/scoreB) were never generated by any
 * endpoint; any found are reported, not touched.
 *
 * USAGE
 * -----
 *   npx ts-node scripts/migrate-tournament-formats.ts           # dry run
 *   npx ts-node scripts/migrate-tournament-formats.ts --apply   # apply
 *
 * Reads MONGODB_URI from .env. Safe to re-run: only old values are matched.
 */
import { config as loadEnv } from 'dotenv';
import mongoose from 'mongoose';

loadEnv();

const APPLY = process.argv.includes('--apply');

const DEFAULT_SETTINGS: Record<string, unknown> = {
  knockout: {
    knockout: {
      legs: 1,
      drawResolution: 'PENALTIES',
      thirdPlaceMatch: false,
      bracketSeeding: 'RANDOM_DRAW',
    },
  },
  league: {
    league: {
      groupCount: 1,
      teamsPerGroup: null,
      roundRobin: 'SINGLE',
      points: { win: 3, draw: 1, loss: 0 },
      groupDraw: 'RANDOM',
      separateSameClub: false,
      tiebreakers: [
        'H2H_POINTS',
        'H2H_GOAL_DIFF',
        'GOAL_DIFF',
        'GOALS_FOR',
        'FAIR_PLAY',
        'LOTS',
      ],
    },
  },
};

async function step(
  label: string,
  coll: mongoose.mongo.Collection,
  filter: object,
  update: object,
) {
  const count = await coll.countDocuments(filter);
  console.log(`  ${label}: ${count}`);
  if (APPLY && count) await coll.updateMany(filter, update);
}

async function main(): Promise<void> {
  const uri = process.env.MONGODB_URI;
  if (!uri) throw new Error('MONGODB_URI is not set (check your .env)');
  await mongoose.connect(uri);
  const db = mongoose.connection.db;
  if (!db) throw new Error('No database handle after connecting');

  console.log(
    APPLY
      ? '=== APPLYING changes ==='
      : '=== DRY RUN (no writes) — pass --apply to commit ===',
  );
  const tournaments = db.collection('tournaments');
  const teams = db.collection('tournamentteams');
  const matches = db.collection('tournamentmatches');

  await step(
    'registering -> REGISTRATION_OPEN',
    tournaments,
    { status: 'registering' },
    { $set: { status: 'REGISTRATION_OPEN' } },
  );
  await step(
    'ongoing knockout -> KNOCKOUT_IN_PROGRESS',
    tournaments,
    { status: 'ongoing', type: 'knockout' },
    { $set: { status: 'KNOCKOUT_IN_PROGRESS' } },
  );
  await step(
    'ongoing league -> LEAGUE_IN_PROGRESS',
    tournaments,
    { status: 'ongoing', type: 'league' },
    { $set: { status: 'LEAGUE_IN_PROGRESS' } },
  );
  await step(
    'finished -> COMPLETED',
    tournaments,
    { status: 'finished' },
    { $set: { status: 'COMPLETED' } },
  );
  for (const type of ['knockout', 'league']) {
    await step(
      `type ${type} -> format ${type.toUpperCase()}`,
      tournaments,
      { type, format: { $exists: false } },
      {
        $set: {
          format: type.toUpperCase(),
          settings: DEFAULT_SETTINGS[type],
          tieResolutions: [],
          placements: [],
        },
      },
    );
  }
  await step(
    'registrations without status -> APPROVED',
    teams,
    { status: { $exists: false } },
    { $set: { status: 'APPROVED', clubId: null, withdrawnAt: null } },
  );

  const legacy = await matches.countDocuments({ scoreA: { $exists: true } });
  if (legacy)
    console.log(
      `  !! ${legacy} legacy tournamentmatches rows (scoreA/scoreB) — review by hand`,
    );

  await mongoose.disconnect();
  console.log(APPLY ? 'Done.' : 'Dry run complete.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
